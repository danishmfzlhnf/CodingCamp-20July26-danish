// Currency Formatter Helper (Rupiah)
function formatRupiah(amount) {
  return "Rp" + Number(amount).toLocaleString("id-ID");
}

// Compact Sold Count Formatter (e.g., 10200 -> "10RB+")
function formatSoldCount(count) {
  if (count >= 10000) {
    const rb = Math.floor(count / 1000);
    return `${rb}RB+ Terjual`;
  } else if (count >= 1000) {
    const k = (count / 1000).toFixed(1).replace(".0", "");
    return `${k}RB Terjual`;
  }
  return `${count} Terjual`;
}
